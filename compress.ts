/**
 * Keep a map bounded: evict the oldest entry when full. Long-running
 * sessions spawn many tasks; unbounded maps would leak memory.
 */
export function boundedMapSet<V>(map: Map<string, V>, key: string, value: V, max = 500): void {
  if (map.size >= max && !map.has(key)) {
    const oldest = map.keys().next().value;
    if (oldest !== undefined) map.delete(oldest);
  }
  map.set(key, value);
}

