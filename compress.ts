// truncate pass (lossy)
// ---------------------------------------------------------------------------

function truncateText(text: string, maxLines: number, maxKB: number): { kept: string; removedChars: number } {
  const lines = text.split('\n');
  if (lines.length > maxLines) {
    const headLines = Math.ceil(maxLines * 0.6);
    const tailLines = maxLines - headLines;
    const head = lines.slice(0, headLines);
    const tail = lines.slice(-tailLines);
    const kept = `${head.join('\n')}\n… [broke: truncated ${lines.length} lines → ${maxLines}] - full output removed\n${tail.join('\n')}`;
    return { kept, removedChars: text.length - kept.length };
  }
  if (text.length > maxKB * 1024) {
    const maxChars = maxKB * 1024;
    const headChars = Math.ceil(maxChars * 0.6);
    const kept = `${text.slice(0, headChars)}\n… [broke: truncated ${Math.round(text.length / 1024)} KB → ${maxKB} KB] - full output removed\n${text.slice(-Math.floor(maxChars * 0.4))}`;
    return { kept, removedChars: text.length - kept.length };
  }
  return { kept: text, removedChars: 0 };
}

export function truncatePass(
  messages: ContextMessage[],
  protectedTurns: number,
  maxLines: number,
  maxKB: number,
  maxInputChars: number,
): PassResult {
  const { start, end } = compressibleRange(messages, protectedTurns);
  if (start >= end) return { messages, removedChars: 0 };

  let removedChars = 0;
  const result = messages.map((msg, i) => {
    if (i < start || i >= end) return msg;

    if (msg.role === 'tool' && Array.isArray(msg.content)) {
      let changed = false;
      const parts = msg.content.map((p) => {
        const part = p as unknown as PartLike;
        if (part.type !== 'tool-result') return p;
        const output = part.output as { type?: string; value?: unknown } | undefined;
        if (!output) return p;
        if (output.type === 'text' || output.type === 'error-text') {
          if (typeof output.value !== 'string') return p;
          const { kept, removedChars: removed } = truncateText(output.value, maxLines, maxKB);
          if (removed > 0) {
            changed = true;
            removedChars += removed;
            return { ...part, output: { ...output, value: kept } };
          }
          return p;
        }
        if (output.type === 'json' || output.type === 'content') {
          // Large structured outputs (codegraph, search results, listings)
          // are truncated too; the payload becomes a marked text preview.
          let serialized: string;
          try {
            serialized = JSON.stringify(output.value);
          } catch {
            return p;
          }
          const { kept, removedChars: removed } = truncateText(serialized, maxLines, maxKB);
          if (removed > 0) {
            changed = true;
            removedChars += removed;
            return { ...part, output: { type: 'text', value: kept } };
          }
          return p;
        }
        return p;
      });
      return changed ? ({ ...msg, content: parts } as unknown as ContextMessage) : msg;
    }

    // Trim oversized tool-call inputs in old assistant messages.
    if (msg.role === 'assistant' && Array.isArray(msg.content)) {
      let changed = false;
      const parts = msg.content.map((p) => {
        const part = p as unknown as PartLike;
        if (part.type !== 'tool-call') return p;
        if (part.input === undefined || part.input === null) return p;
        let inputText: string;
        try {
          inputText = JSON.stringify(part.input);
        } catch {
          return p;
        }
        if (inputText.length <= maxInputChars) return p;
        const preview = inputText.slice(0, 400);
        const trimmed = { __broke: 'input truncated (not re-executable)', originalChars: inputText.length, preview };
        changed = true;
        removedChars += inputText.length - JSON.stringify(trimmed).length;
        return { ...part, input: trimmed };
      });
      return changed ? ({ ...msg, content: parts } as unknown as ContextMessage) : msg;
    }

    return msg;
  });

  return { messages: result, removedChars };
}

// ---------------------------------------------------------------------------
// error pass (lossy) - stack-trace & log compression
// ---------------------------------------------------------------------------

export interface ErrorPassOptions {
  /** Compress matching tool results with at least this many chars. */
  minChars: number;
  /** Context lines kept around the failing line. */
  contextLines: number;
}

/**
 * Replace old tool results that are compiler/test error output with their
 * diagnostic essence (exception type, failing file:line, small context
 * window). Per-message threshold, independent of maxContextChars: a 2k-line
 * test failure in a small conversation is exactly the case worth
 * compressing. Runs BEFORE the truncate pass so extraction sees the full
 * text; truncate then handles whatever remains. Input-only - the stored
 * task history is never touched.
 */
export function errorPass(messages: ContextMessage[], protectedTurns: number, opts: ErrorPassOptions): PassResult {
  const { start, end } = compressibleRange(messages, protectedTurns);
  if (start >= end) return { messages, removedChars: 0 };

  let removedChars = 0;
  const result = messages.map((msg, i) => {
    if (i < start || i >= end || msg.role !== 'tool' || !Array.isArray(msg.content)) return msg;

    let changed = false;
    const parts = msg.content.map((p) => {
      const part = p as unknown as PartLike;
      if (part.type !== 'tool-result') return p;
      const output = part.output as { type?: string; value?: unknown } | undefined;
      if (!output) return p;
      // Inspect the output's error-relevant text: plain text payloads AND the
      // stdout/stderr of structured command outputs (power---bash, test runs).
      const outputText = extractOutputText(output);
      if (outputText === null || outputText.text.length < opts.minChars) return p;

      // Same redaction policy as the tool-level path: an error summary must
      // never carry secrets from the underlying tool output.
      const extracted = extractErrorSummary(maskSecrets(outputText.text), { contextLines: opts.contextLines });
      if (!extracted.matched) return p;
      changed = true;
      // Marker mirrors the truncate pass so the model/user can see the cut:
      // "… [broke: error summary - N lines → M lines] - full output removed".
      const summary = formatErrorSummary(extracted, ' - full output removed');
      removedChars += outputText.text.length - summary.length;
      return { ...part, output: outputText.wrap(summary) };
    });
    return changed ? ({ ...msg, content: parts } as unknown as ContextMessage) : msg;
  });

  return { messages: result, removedChars };
}

