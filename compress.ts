// truncate pass (lossy)
// ---------------------------------------------------------------------------

function truncateText(text: string, maxLines: number, maxKB: number): { kept: string; removedChars: number } {
  const maxChars = maxKB * 1024;
  const lines = text.split('\n');
  const overLines = lines.length > maxLines;
  const overChars = text.length > maxChars;
  if (!overLines && !overChars) return { kept: text, removedChars: 0 };

  // Pass 1 (content only): cut to head+tail lines. The marker is added
  // afterwards so BOTH passes can report in a single marker line.
  let headText: string;
  let tailText: string;
  if (overLines) {
    const headLines = Math.ceil(maxLines * 0.6);
    const tailLines = maxLines - headLines;
    headText = lines.slice(0, headLines).join('\n');
    // tailLines can be 0 for maxLines 1-2; lines.slice(-0) returns the WHOLE
    // array in JS, which would silently keep everything (or worse). Compute
    // the tail from the end index instead - slice(length) is always empty.
    tailText = tailLines > 0 ? lines.slice(lines.length - tailLines).join('\n') : '';
  } else {
    headText = text;
    tailText = '';
  }

  // XF5: the line pass alone does not guarantee the KB cap - a few very long
  // lines can exceed it. Enforce the char cap as a HARD limit after the line
  // pass, with the marker budgeted in, so the result never exceeds maxKB
  // (marker included). The cut only runs when the line-passed body is STILL
  // over the cap (the line pass may already have brought it under).
  const body = overLines ? `${headText}\n${tailText}` : headText;
  if (body.length > maxChars) {
    const cutParts = [
      overLines ? `${lines.length} lines → ${maxLines} lines` : null,
      `${Math.round(text.length / 1024)} KB → ${maxKB} KB`,
    ].filter((p): p is string => p !== null);
    const marker = `… [broke: truncated ${cutParts.join(', ')}] - full output removed`;
    const budget = Math.max(maxChars - marker.length - 2, 1);
    const headChars = Math.min(Math.ceil(budget * 0.6), budget);
    const tailChars = budget - headChars;
    const headPart = body.slice(0, headChars);
    const tailPart = tailChars > 0 ? body.slice(body.length - tailChars) : '';
    const kept = `${headPart}\n${marker}\n${tailPart}`;
    return { kept, removedChars: text.length - kept.length };
  }

  const marker = `… [broke: truncated ${lines.length} lines → ${maxLines}] - full output removed`;
  const kept = `${headText}\n${marker}\n${tailText}`;
  return { kept, removedChars: text.length - kept.length };
}

export function truncatePass(
  messages: ContextMessage[],
  protectedTurns: number,
  maxLines: number,
  maxKB: number,
  maxInputChars: number,
): PassResult {
  const { start, end } = compressibleRange(messages, protectedTurns);
  if (start >= end) return { messages, removedChars: 0 };

  let removedChars = 0;
  const result = messages.map((msg, i) => {
    if (i < start || i >= end) return msg;

    if (msg.role === 'tool' && Array.isArray(msg.content)) {
      let changed = false;
      const parts = msg.content.map((p) => {
        const part = p as unknown as PartLike;
        if (part.type !== 'tool-result') return p;
        const output = part.output as { type?: string; value?: unknown } | undefined;
        if (!output) return p;
        if (output.type === 'text' || output.type === 'error-text') {
          if (typeof output.value !== 'string') return p;
          const { kept, removedChars: removed } = truncateText(output.value, maxLines, maxKB);
          if (removed > 0) {
            changed = true;
            removedChars += removed;
            return { ...part, output: { ...output, value: kept } };
          }
          return p;
        }
        if (output.type === 'json' || output.type === 'content') {
          // Structured command outputs ({ stdout, stderr, exitCode, ... })
          // keep their shape and metadata (XF7): only the text payload is
          // truncated via the canonical extractor, stderr is emptied, and
          // exitCode/other fields survive.
          const extracted = extractOutputText(output);
          if (extracted && extracted.text.length > 0) {
            const { kept, removedChars: removed } = truncateText(extracted.text, maxLines, maxKB);
            if (removed > 0) {
              changed = true;
              removedChars += removed;
              return { ...part, output: extracted.wrap(kept) };
            }
          }
          // No text payload worth truncating (pure JSON data): the payload
          // becomes a marked text preview. A truncated JSON document is not
          // valid JSON, so it must not keep the json type.
          let serialized: string;
          try {
            serialized = JSON.stringify(output.value);
          } catch {
            return p;
          }
          const { kept, removedChars: removed } = truncateText(serialized, maxLines, maxKB);
          if (removed > 0) {
            changed = true;
            removedChars += removed;
            return { ...part, output: { type: 'text', value: kept } };
          }
          return p;
        }
        return p;
      });
      return changed ? ({ ...msg, content: parts } as unknown as ContextMessage) : msg;
    }

    // Trim oversized tool-call inputs in old assistant messages.
    if (msg.role === 'assistant' && Array.isArray(msg.content)) {
      let changed = false;
      const parts = msg.content.map((p) => {
        const part = p as unknown as PartLike;
        if (part.type !== 'tool-call') return p;
        if (part.input === undefined || part.input === null) return p;
        let inputText: string;
        try {
          inputText = JSON.stringify(part.input);
        } catch {
          return p;
        }
        if (inputText.length <= maxInputChars) return p;
        const preview = inputText.slice(0, 400);
        const trimmed = { __broke: 'input truncated (not re-executable)', originalChars: inputText.length, preview };
        changed = true;
        removedChars += inputText.length - JSON.stringify(trimmed).length;
        return { ...part, input: trimmed };
      });
      return changed ? ({ ...msg, content: parts } as unknown as ContextMessage) : msg;
    }

    return msg;
  });

  return { messages: result, removedChars };
}

