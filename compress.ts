export interface ErrorPassOptions {
  /** Compress matching tool results with at least this many chars. */
  minChars: number;
  /** Context lines kept around the failing line. */
  contextLines: number;
}

/**
 * Replace old tool results that are compiler/test error output with their
 * diagnostic essence (exception type, failing file:line, small context
 * window). Per-message threshold, independent of maxContextChars: a 2k-line
 * test failure in a small conversation is exactly the case worth
 * compressing. Runs BEFORE the truncate pass so extraction sees the full
 * text; truncate then handles whatever remains. Input-only - the stored
 * task history is never touched.
 */
export function errorPass(messages: ContextMessage[], protectedTurns: number, opts: ErrorPassOptions): PassResult {
  const { start, end } = compressibleRange(messages, protectedTurns);
  if (start >= end) return { messages, removedChars: 0 };

  let removedChars = 0;
  const result = messages.map((msg, i) => {
    if (i < start || i >= end || msg.role !== 'tool' || !Array.isArray(msg.content)) return msg;

    let changed = false;
    const parts = msg.content.map((p) => {
      const part = p as unknown as PartLike;
      if (part.type !== 'tool-result') return p;
      // Only command/compiler/test tools produce error-shaped output that is
      // safe to compress. File reads, search results, docs etc. can
      // legitimately contain lines that look like errors ("Error:" headings,
      // markdown ● bullets, ✕ checklists) - compressing those would corrupt
      // the model's view of the file. Same guard as the tool-level path.
      if (!isCommandTool(typeof part.toolName === 'string' ? part.toolName : '')) return p;
      const output = part.output as { type?: string; value?: unknown } | undefined;
      if (!output) return p;
      // Inspect the output's error-relevant text: plain text payloads AND the
      // stdout/stderr of structured command outputs (power---bash, test runs).
      const outputText = extractOutputText(output);
      if (outputText === null || outputText.text.length < opts.minChars) return p;

      // Same redaction policy as the tool-level path: an error summary must
      // never carry secrets from the underlying tool output.
      const extracted = extractErrorSummary(maskSecrets(outputText.text), { contextLines: opts.contextLines });
      if (!extracted.matched) return p;
      // Marker mirrors the truncate pass so the model/user can see the cut:
      // "… [broke: error summary - N lines → M lines] - full output removed".
      const summary = formatErrorSummary(extracted, ' - full output removed');
      // XF6 consistency, D2 decision (review F-08): never GROW the context.
      // The old code rewrote even when the summary was LONGER than the
      // original (clamping the reported savings to 0). Skipping keeps the
      // original - in that edge case the unredacted text simply stays until
      // the summarize/truncate passes handle it, exactly like every other
      // noop guard. With the shipped defaults (minChars 8000) an oversize
      // summary is practically impossible anyway.
      if (summary.length >= outputText.text.length) return p;
      const removed = outputText.text.length - summary.length;
      changed = true;
      removedChars += removed;
      return { ...part, output: outputText.wrap(summary) };
    });
    return changed ? ({ ...msg, content: parts } as unknown as ContextMessage) : msg;
  });

  return { messages: result, removedChars };
}

