/**
 * Content-based pipeline gate (review F-10). The old `messages.length < 4`
 * check excluded small contexts ENTIRELY - a short-but-fat context (a huge
 * error tool result in a 3-message loop) never reached the error pass. The
 * only lossy pass that can fire below `maxContextChars` is error compression
 * (per-message `errors.minChars`), so a short context proceeds when its
 * content could actually trip that threshold; the region/pairing math then
 * decides what is safely compressible. Long contexts always proceed.
 */
export function shouldCompress(messages: ContextMessage[], config: Config, totalChars?: number): boolean {
  if (!config.enabled) return false;
  if (messages.length >= 4) return true;
  return (totalChars ?? messagesChars(messages)) >= config.errors.minChars;
}

export async function compressMessages(
  messages: ContextMessage[],
  config: Config,
  deps: SummarizeDeps,
  state: CompressState,
  taskId: string,
  opts: CompressOptions = {},
): Promise<{ messages: ContextMessage[]; report: CompressReport }> {
  const totalCharsBefore = messagesChars(messages);
  const report = emptyReport(totalCharsBefore);

  if (!shouldCompress(messages, config, totalCharsBefore)) {
    return { messages, report };
  }

  let work = messages;

  // Pass 1 - structural (lossless, synchronous, cannot throw).
  const structural = structuralPass(work, config.protectedTurns);
  report.structuralChars = structural.removedChars;
  work = structural.messages;

  const { start, end } = compressibleRange(work, config.protectedTurns);
  const hasOldContent = start < end;

  // Pass 2 - error compression (lossy, synchronous, cannot throw). Runs
  // BEFORE truncate so stack-trace extraction sees the full output text.
  if ((config.level === 'truncate' || config.level === 'summarize') && hasOldContent && config.errors.enabled) {
    const errors = errorPass(work, config.protectedTurns, { minChars: config.errors.minChars, contextLines: config.errors.contextLines });
    report.errorChars = errors.removedChars;
    work = errors.messages;
  }

  // Pass 3 - truncate (lossy, synchronous, cannot throw).
  if ((config.level === 'truncate' || config.level === 'summarize') && hasOldContent && totalCharsBefore > config.maxContextChars) {
    const truncated = truncatePass(work, config.protectedTurns, config.truncate.maxLines, config.truncate.maxKB, config.truncate.maxInputChars);
    report.truncateChars = truncated.removedChars;
    work = truncated.messages;
  }

  // Pass 4 - summarize (lossy, LLM). Isolated: a summarizer failure must not
  // discard the structural/truncate savings nor break the model call.
  if (config.level === 'summarize' && !opts.summarizeDisabled && totalCharsBefore > config.maxContextChars) {
    try {
      const summarized = await summarizePass(work, config.protectedTurns, config, deps, state, taskId);
      report.summarizeChars = summarized.removedChars;
      report.summarizedRanges = summarized.summarizedRanges;
      report.summarizeCalls = summarized.summarizeCalls;
      report.summarizeFailed = summarized.failed;
      report.summarizerInputChars = summarized.summarizerInputChars;
      report.summarizerOutputChars = summarized.summarizerOutputChars;
      if (summarized.summarizer !== 'none') {
        report.summarizer = summarized.summarizer;
      }
      work = summarized.messages;
    } catch {
      // summarizePass guards its internals; this is a last-resort net.
      report.summarizeFailed = true;
    }
  }

  report.totalCharsAfter = messagesChars(work);

  // ContextValidator (review P0): the pipeline must never INTRODUCE a broken
  // context. Revert happens only when the OUTPUT violates pairing/identity
  // invariants while the INPUT was sound - i.e. a pass broke it. When the
  // input was already corrupt, the provider call fails either way (that is a
  // pre-existing host/history condition, not something compression caused),
  // and reverting would silently disable broke for every subsequent call on
  // that task - so the compressed output ships unchanged. Fail-safe over
  // fail-broken, without turning the guard into a compression kill-switch.
  const validate = opts.validate ?? validateContext;
  const outputFailures = validate(work);
  if (outputFailures.length > 0 && validate(messages).length === 0) {
    opts.onValidationFailure?.(
      `broke: context validation failed (${formatValidationFailures(outputFailures)}) - reverting to the uncompressed context`,
    );
    const reverted = emptyReport(totalCharsBefore);
    reverted.summarizeCalls = report.summarizeCalls;
    reverted.summarizeFailed = report.summarizeFailed;
    reverted.summarizerInputChars = report.summarizerInputChars;
    reverted.summarizerOutputChars = report.summarizerOutputChars;
    if (report.summarizer !== 'none') reverted.summarizer = report.summarizer;
    return { messages, report: reverted };
  }

  report.touched =
    report.structuralChars + report.errorChars + report.truncateChars + report.summarizeChars > 0 ||
    report.summarizedRanges > 0 ||
    report.summarizeFailed;

  return { messages: work, report };
}
