export function isSummaryMessage(message: ContextMessage): boolean {
  if (message.role !== 'assistant' || typeof message.content !== 'string') return false;
  return message.content.startsWith(SUMMARY_MARKER);
}

/**
 * Number of trailing messages kept untouched when a session has fewer user
 * turns than `protectedTurns` (the common AiderDesk pattern: one task brief
 * followed by a long tool loop). Only the current step stays readable; the
 * rest of the loop becomes compressible.
 */
export const ACTIVE_TURN_TAIL = 5;

/**
 * Find the compressible region: after the first user message (task brief),
 * before the last `protectedTurns` user turns. Sessions with fewer user
 * turns fall back to protecting only the last `ACTIVE_TURN_TAIL` messages,
 * so a single-prompt tool loop is still compressible instead of being
 * treated as one giant "working set".
 */
/**
 * Pairing safety: a region boundary must never split a tool-call /
 * tool-result pair. If the message directly after `end` is a tool result
 * whose producing call sits at the region's edge, replacing or summarizing
 * [start, end) would remove the call and ORPHAN its result - which makes
 * the next provider call fail. The same applies at `start`: a region that
 * begins with a tool result would lose its holder into whatever sits
 * before the region. Shrink the region past tool results on both edges;
 * losing a little compression is always better than breaking the model
 * call.
 */
function clampRegionToPairs(messages: ContextMessage[], start: number, end: number): { start: number; end: number } {
  while (end > start && messages[end]?.role === 'tool') end--;
  while (start < end && messages[start].role === 'tool') start++;
  return { start, end };
}

export function compressibleRange(messages: ContextMessage[], protectedTurns: number): { start: number; end: number } {
  const firstUser = messages.findIndex((m) => m.role === 'user');
  if (firstUser === -1) return { start: 0, end: 0 };

  let seen = 0;
  let end = messages.length;
  for (let i = messages.length - 1; i >= 0; i--) {
    if (messages[i].role === 'user') {
      seen++;
      if (seen >= protectedTurns) {
        end = i;
        break;
      }
    }
  }
  if (seen < protectedTurns) {
    // Not enough user turns for the turn-based protection: keep only the
    // current step (task brief + last messages) untouched.
    end = Math.max(firstUser + 1, messages.length - ACTIVE_TURN_TAIL);
  }
  return clampRegionToPairs(messages, Math.max(firstUser + 1, 1), Math.max(end, firstUser + 1));
}

interface PartLike {
  type: string;
  [key: string]: unknown;
}

function assistantText(message: ContextMessage): string {
  if (typeof message.content === 'string') return message.content;
  if (Array.isArray(message.content)) {
    return message.content
      .filter((p): p is { type: 'text'; text: string } => (p as unknown as PartLike).type === 'text')
      .map((p) => p.text)
      .join('\n');
  }
  return '';
}

function hasToolCalls(message: ContextMessage): boolean {
  return Array.isArray(message.content) && message.content.some((p) => (p as unknown as PartLike).type === 'tool-call');
}

/** True when the message content is absent, a string, or an array of ONLY text parts. */
function isTextOnly(message: ContextMessage): boolean {
  if (typeof message.content === 'string') return true;
  if (!Array.isArray(message.content)) return true;
  return message.content.every((p) => (p as unknown as PartLike).type === 'text');
}

/** True when the message carries parts that are neither text nor tool-calls (image, reasoning, …). */
function hasRichParts(message: ContextMessage): boolean {
  if (!Array.isArray(message.content)) return false;
  return message.content.some((p) => {
    const type = (p as unknown as PartLike).type;
    return type !== 'text' && type !== 'tool-call';
  });
}

/**
 * True when a message carries parts that summarization cannot turn into
 * text: images, files, reasoning (dropped by partText) and tool results
 * whose output type has no text extraction. Summarize-level compression is
 * lossy by contract, but these parts would be dropped SILENTLY, so the pass
 * must skip regions containing them instead.
 */
function hasUnsummarizableParts(message: ContextMessage): boolean {
  if (!Array.isArray(message.content)) return false;
  return message.content.some((p) => {
    const part = p as unknown as PartLike;
    if (part.type === 'tool-result') {
      const output = part.output as { type?: string } | undefined;
      const type = output?.type ?? '';
      return !['text', 'error-text', 'json', 'error-json', 'content'].includes(type);
    }
    return part.type !== 'text' && part.type !== 'tool-call';
  });
}

// ---------------------------------------------------------------------------
// structural pass (lossless)
// ---------------------------------------------------------------------------

export interface PassResult {
  messages: ContextMessage[];
  removedChars: number;
}

export function structuralPass(messages: ContextMessage[], protectedTurns: number): PassResult {
  const { start, end } = compressibleRange(messages, protectedTurns);
  if (start >= end) return { messages, removedChars: 0 };

  const result: ContextMessage[] = [];
  let removedChars = 0;

  for (let i = 0; i < messages.length; i++) {
    const msg = messages[i];
    const inRegion = i >= start && i < end;

    // Drop assistant messages that carry no text, no tool calls and no rich
    // parts (reasoning/image must never be silently discarded).
    if (inRegion && msg.role === 'assistant' && !isSummaryMessage(msg) && !hasRichParts(msg)) {
      const text = assistantText(msg);
      if (!hasToolCalls(msg) && !text.trim()) {
        removedChars += messageChars(msg);
        continue;
      }
    }

    // Drop empty tool results inside a tool message (keep the rest), and
    // dedupe repeated tool results. Both only ever happen TOGETHER with
    // their matching assistant tool-calls - a tool-call without a result
    // makes the provider call fail (AI_MissingToolResultsError). Dedupe
    // additionally requires the producing tool-calls to be identical
    // (name + input): equal outputs alone are not enough (XF1).
    if (inRegion && msg.role === 'tool' && Array.isArray(msg.content)) {
      const parts = msg.content as unknown as PartLike[];
      const emptyParts = parts.filter(
        (p) => p.type === 'tool-result' && partText(p).trim().length === 0,
      );
      let working: ContextMessage = msg;
      if (emptyParts.length > 0) {
        const removedPair = removeToolResultsWithCalls(result, msg, emptyParts);
        if (removedPair > 0) {
          removedChars += removedPair;
          const keptParts = parts.filter((p) => !emptyParts.includes(p));
          if (keptParts.length === 0) continue; // whole message and its calls are gone
          working = { ...msg, content: keptParts } as unknown as ContextMessage;
        }
        // Pairing could not be completed: keep the message untouched so no
        // tool-call loses its result.
      }
      if (i > 0 && isDuplicateToolResult(result, working)) {
        const allParts = Array.isArray(working.content) ? (working.content as unknown as PartLike[]) : [];
        const removedPair = removeToolResultsWithCalls(result, working, allParts);
        if (removedPair > 0) {
          removedChars += removedPair;
          continue;
        }
        // Abort the dedupe rather than orphan a tool-call.
      }
      result.push(working);
      continue;
    }

    // Merge consecutive assistant text messages - only when BOTH sides are
    // pure text (merging would otherwise drop reasoning/image parts).
    if (inRegion && msg.role === 'assistant' && !hasToolCalls(msg) && isTextOnly(msg) && result.length > 0) {
      const prev = result[result.length - 1];
      if (prev.role === 'assistant' && !hasToolCalls(prev) && isTextOnly(prev) && !isSummaryMessage(prev)) {
        const mergedText = [assistantText(prev), assistantText(msg)].filter(Boolean).join('\n\n');
        // Honest accounting: the merged text stays in the context (plus the
        // separator), so a merge saves 0 chars. Only the message framing
        // overhead shrinks, which messageChars does not model - counting the
        // merged-away message as saved would report phantom savings.
        result[result.length - 1] = {
          ...prev,
          content: mergedText ? [{ type: 'text', text: mergedText }] : prev.content,
        };
        continue;
      }
    }

    result.push(msg);
  }

  return { messages: result, removedChars };
}

/** True when two tool messages carry identical results (same part count, tool names and output text). */
function sameToolResult(a: ContextMessage, b: ContextMessage): boolean {
  const aParts = Array.isArray(a.content) ? (a.content as unknown as PartLike[]) : [];
  const bParts = Array.isArray(b.content) ? (b.content as unknown as PartLike[]) : [];
  if (aParts.length === 0 || aParts.length !== bParts.length) return false;
  for (let i = 0; i < aParts.length; i++) {
    const x = aParts[i];
    const y = bParts[i];
    if (x.type !== 'tool-result' || y.type !== 'tool-result') return false;
    if (x.toolName !== y.toolName) return false;
    if (partText(x) !== partText(y)) return false;
  }
  return true;
}

/**
 * True when `current` repeats a tool result that is still in `result`:
 * either the immediately preceding tool message (parallel calls) or the
 * result two messages back behind an assistant message (repeated call
 * sequence). XF1: the result identity alone is not enough - the producing
 * tool-calls (name + input) must be identical too.
 */
function isDuplicateToolResult(result: ContextMessage[], current: ContextMessage): boolean {
  if (result.length < 1) return false;
  const prev = result[result.length - 1];
  if (prev.role === 'tool') return sameToolResult(prev, current) && sameProducingCalls(result, prev, current);
  if (prev.role === 'assistant' && result.length >= 2) {
    const prevResult = result[result.length - 2];
    if (prevResult.role === 'tool') {
      return sameToolResult(prevResult, current) && sameProducingCalls(result, prevResult, current);
    }
  }
  return false;
}

/** Call ids of a tool message's tool-result parts, in part order. */
function resultCallIds(msg: ContextMessage): string[] {
  if (!Array.isArray(msg.content)) return [];
  return (msg.content as unknown as PartLike[])
    .filter((p) => p.type === 'tool-result' && typeof p.toolCallId === 'string')
    .map((p) => p.toolCallId as string);
}

/** Stable signature of a tool-call part: tool name + serialized input. */
function toolCallSignature(p: PartLike): string {
  let input: string;
  try {
    input = JSON.stringify(p.input ?? null);
  } catch {
    input = String(p.input);
  }
  return `${p.toolName ?? ''}::${input}`;
}

/** Signatures of the holder's tool-call parts for `ids`, in `ids` order (null when a call is missing). */
function callSignaturesByHolder(holder: ContextMessage, ids: string[]): string[] | null {
  if (!Array.isArray(holder.content)) return null;
  const byId = new Map<string, string>();
  for (const p of holder.content as unknown as PartLike[]) {
    if (p.type === 'tool-call' && typeof p.toolCallId === 'string' && ids.includes(p.toolCallId)) {
      byId.set(p.toolCallId, toolCallSignature(p));
    }
  }
  if (byId.size !== ids.length) return null;
  return ids.map((id) => byId.get(id) as string);
}

/**
 * XF1: identical outputs are not enough for dedupe - the tool calls that
 * PRODUCED them must be identical too (same tool name and input, pairwise
 * per call id). Two different actions with coincidentally equal results
 * (bash "echo 1" vs bash "printf '1'") are different history and must both
 * stay in the context. Conservative on every uncertain path: missing
 * holders, partial call sets or unserializable inputs all abort the dedupe.
 */
function sameProducingCalls(result: ContextMessage[], prev: ContextMessage, current: ContextMessage): boolean {
  const prevIds = resultCallIds(prev);
  const currIds = resultCallIds(current);
  if (prevIds.length === 0 || prevIds.length !== currIds.length) return false;
  const prevHolder = findCallHolder(result, prevIds);
  const currHolder = findCallHolder(result, currIds);
  if (!prevHolder || !currHolder) return false;
  const prevSignatures = callSignaturesByHolder(prevHolder, prevIds);
  const currSignatures = callSignaturesByHolder(currHolder, currIds);
  if (!prevSignatures || !currSignatures) return false;
  return prevSignatures.every((sig, i) => sig === currSignatures[i]);
}

/**
 * Remove the given tool-result parts of `current` together with the
 * assistant tool-calls they answer. The pairing invariant is absolute:
 * every remaining assistant tool-call must keep its result, so when the
 * holder (the assistant message containing the calls) cannot be found or
 * does not contain ALL affected call ids, NOTHING is removed - keeping the
 * duplicate is always safer than orphaning a call (an orphaned tool-call
 * makes the provider call fail). Returns the number of removed chars
 * (0 = nothing changed).
 */
function removeToolResultsWithCalls(
  result: ContextMessage[],
  current: ContextMessage,
  removedParts: PartLike[],
): number {
  const callIds = removedParts
    .filter((p) => p.type === 'tool-result' && typeof p.toolCallId === 'string')
    .map((p) => p.toolCallId as string);
  if (callIds.length === 0) return 0;

  const holder = findCallHolder(result, callIds);
  if (!holder || !Array.isArray(holder.content)) return 0;

  const holderParts = holder.content as unknown as PartLike[];
  const ids = new Set(callIds);
  const kept = holderParts.filter(
    (p) => !(p.type === 'tool-call' && typeof p.toolCallId === 'string' && ids.has(p.toolCallId)),
  );
  if (holderParts.length - kept.length !== callIds.length) return 0; // a call is missing → abort

  let removed = messageChars(current);
  const currentParts = Array.isArray(current.content) ? (current.content as unknown as PartLike[]) : [];
  const keptMessageParts = currentParts.filter((p) => !removedParts.includes(p));
  if (keptMessageParts.length > 0) {
    removed -= messageChars({ ...current, content: keptMessageParts } as unknown as ContextMessage);
  }
  removed += messageChars(holder) - messageChars({ ...holder, content: kept } as unknown as ContextMessage);

  const idx = result.indexOf(holder);
  if (idx !== -1) {
    if (kept.length === 0) {
      result.splice(idx, 1);
    } else {
      result[idx] = { ...holder, content: kept } as unknown as ContextMessage;
    }
  }
  return removed;
}

/**
 * Find the most recent assistant message holding ANY of the given
 * tool-call ids. Searches the whole accumulated result - compactions can
 * remove interleaving messages, so the holder is not always adjacent.
 */
function findCallHolder(result: ContextMessage[], callIds: string[]): ContextMessage | null {
  const ids = new Set(callIds);
  for (let k = result.length - 1; k >= 0; k--) {
    const m = result[k];
    if (m.role !== 'assistant' || !Array.isArray(m.content)) continue;
    const has = (m.content as unknown as PartLike[]).some(
      (p) => p.type === 'tool-call' && typeof p.toolCallId === 'string' && ids.has(p.toolCallId),
    );
    if (has) return m;
  }
  return null;
}

